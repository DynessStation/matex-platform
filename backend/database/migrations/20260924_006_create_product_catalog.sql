  CONSTRAINT `fk_product_category_category` FOREIGN KEY (`id_product_category`,`id_master_comp`) REFERENCES `product_category` (`id_product_category`,`id_master_comp`) ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE `product_catalog_attachment` (
