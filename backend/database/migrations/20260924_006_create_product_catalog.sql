CREATE TABLE `product_catalog` (
  `id_product` int NOT NULL AUTO_INCREMENT,
  `id_master_comp` int NOT NULL,
  `product_key` varchar(120) NOT NULL,
  `product_sku` varchar(120) NOT NULL,
  `product_type` varchar(30) NOT NULL DEFAULT 'physical',
  `product_status` varchar(20) NOT NULL DEFAULT 'draft',
  `product_unit` varchar(40) DEFAULT NULL,
  `product_barcode` varchar(120) DEFAULT NULL,
  `product_manufacturer_code` varchar(120) DEFAULT NULL,
  `product_country_origin` varchar(100) DEFAULT NULL,
  `product_hs_code` varchar(50) DEFAULT NULL,
  `product_weight_grams` decimal(12,3) DEFAULT NULL,
  `product_length_mm` decimal(12,3) DEFAULT NULL,
  `product_width_mm` decimal(12,3) DEFAULT NULL,
  `product_height_mm` decimal(12,3) DEFAULT NULL,
  `product_min_order_qty` decimal(12,3) NOT NULL DEFAULT 1,
  `product_lead_time_days` int DEFAULT NULL,
  `product_manage_stock` tinyint(1) NOT NULL DEFAULT 0,
  `product_stock_quantity` decimal(14,3) DEFAULT NULL,
  `product_stock_status` varchar(30) NOT NULL DEFAULT 'in_stock',
  `product_price_visibility` varchar(30) NOT NULL DEFAULT 'contact',
  `product_internal_commerce_enabled` tinyint(1) NOT NULL DEFAULT 0,
  `product_is_featured` tinyint(1) NOT NULL DEFAULT 0,
  `product_sort_order` int NOT NULL DEFAULT 0,
  `id_created_by` int DEFAULT NULL,
  `id_updated_by` int DEFAULT NULL,
  `created` datetime NOT NULL DEFAULT current_timestamp(),
  `updated` datetime NOT NULL DEFAULT current_timestamp() ON UPDATE current_timestamp(),
  `product_deleted_at` datetime DEFAULT NULL,
  PRIMARY KEY (`id_product`),
  UNIQUE KEY `uq_product_company_id` (`id_product`,`id_master_comp`),
  UNIQUE KEY `uq_product_company_key` (`id_master_comp`,`product_key`),
  UNIQUE KEY `uq_product_company_sku` (`id_master_comp`,`product_sku`),
  KEY `idx_product_public` (`id_master_comp`,`product_status`,`product_sort_order`),
  CONSTRAINT `fk_product_company` FOREIGN KEY (`id_master_comp`) REFERENCES `master_comp` (`id_master_comp`) ON UPDATE CASCADE,
  CONSTRAINT `fk_product_created_by` FOREIGN KEY (`id_created_by`) REFERENCES `admin_acct` (`id_admin_acct`) ON DELETE SET NULL ON UPDATE CASCADE,
  CONSTRAINT `fk_product_updated_by` FOREIGN KEY (`id_updated_by`) REFERENCES `admin_acct` (`id_admin_acct`) ON DELETE SET NULL ON UPDATE CASCADE,
  CONSTRAINT `chk_product_type` CHECK (`product_type` IN ('physical','service','digital')),
  CONSTRAINT `chk_product_status` CHECK (`product_status` IN ('draft','published','archived')),
  CONSTRAINT `chk_product_stock_status` CHECK (`product_stock_status` IN ('in_stock','out_of_stock','preorder','made_to_order')),
  CONSTRAINT `chk_product_price_visibility` CHECK (`product_price_visibility` IN ('displayed','contact','hidden'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

