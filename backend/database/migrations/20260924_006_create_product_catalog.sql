  CONSTRAINT `chk_product_attachment_role` CHECK (`product_attachment_role` IN ('thumbnail','gallery','og','size_chart','document'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

