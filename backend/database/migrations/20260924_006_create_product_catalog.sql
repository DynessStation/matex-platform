CREATE TABLE `product_catalog_category` (
  `id_product` int NOT NULL,
  `id_product_category` int NOT NULL,
  `id_master_comp` int NOT NULL,
  `is_primary` tinyint(1) NOT NULL DEFAULT 0,
  `sort_order` int NOT NULL DEFAULT 0,
