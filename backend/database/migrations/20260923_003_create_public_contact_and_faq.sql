  CONSTRAINT `chk_contact_inquiry_locale` CHECK (`contact_inquiry_locale` IN ('id-ID', 'en-US')),
  CONSTRAINT `chk_contact_inquiry_status` CHECK (`contact_inquiry_status` IN ('new', 'in_progress', 'resolved', 'spam', 'closed')),
  CONSTRAINT `chk_contact_inquiry_contact` CHECK (`contact_inquiry_email` IS NOT NULL OR `contact_inquiry_phone` IS NOT NULL)
