CREATE TABLE `public_contact_channel` (
  `id_public_contact_channel` int(11) NOT NULL AUTO_INCREMENT,
  `id_master_comp` int(11) NOT NULL,
  `public_contact_channel_key` varchar(100) NOT NULL,
  `public_contact_channel_type` varchar(30) NOT NULL,
  `public_contact_channel_value` varchar(500) NOT NULL,
  `public_contact_channel_url` varchar(1000) DEFAULT NULL,
  `public_contact_channel_is_primary` tinyint(1) NOT NULL DEFAULT 0,
  `public_contact_channel_is_public` tinyint(1) NOT NULL DEFAULT 1,
  `public_contact_channel_sort_order` int(11) NOT NULL DEFAULT 0,
  `public_contact_channel_settings_json` longtext CHARACTER SET utf8mb4 COLLATE utf8mb4_bin DEFAULT NULL CHECK (json_valid(`public_contact_channel_settings_json`)),
  `id_created_by` int(11) DEFAULT NULL,
  `id_updated_by` int(11) DEFAULT NULL,
  `created` datetime NOT NULL DEFAULT current_timestamp(),
  `updated` datetime NOT NULL DEFAULT current_timestamp() ON UPDATE current_timestamp(),
  `public_contact_channel_deleted_at` datetime DEFAULT NULL,
  PRIMARY KEY (`id_public_contact_channel`),
  UNIQUE KEY `uq_public_contact_channel_id_company` (`id_public_contact_channel`, `id_master_comp`),
  UNIQUE KEY `uq_public_contact_channel_company_key` (`id_master_comp`, `public_contact_channel_key`),
  KEY `idx_public_contact_channel_public` (`id_master_comp`, `public_contact_channel_is_public`, `public_contact_channel_sort_order`),
  KEY `idx_public_contact_channel_created_by` (`id_created_by`),
  KEY `idx_public_contact_channel_updated_by` (`id_updated_by`),
  CONSTRAINT `fk_public_contact_channel_company` FOREIGN KEY (`id_master_comp`) REFERENCES `master_comp` (`id_master_comp`) ON UPDATE CASCADE,
  CONSTRAINT `fk_public_contact_channel_created_by` FOREIGN KEY (`id_created_by`) REFERENCES `admin_acct` (`id_admin_acct`) ON DELETE SET NULL ON UPDATE CASCADE,
  CONSTRAINT `fk_public_contact_channel_updated_by` FOREIGN KEY (`id_updated_by`) REFERENCES `admin_acct` (`id_admin_acct`) ON DELETE SET NULL ON UPDATE CASCADE,
  CONSTRAINT `chk_public_contact_channel_type` CHECK (`public_contact_channel_type` IN ('whatsapp', 'email', 'phone', 'social', 'website', 'other')),
  CONSTRAINT `chk_public_contact_channel_primary` CHECK (`public_contact_channel_is_primary` IN (0, 1)),
  CONSTRAINT `chk_public_contact_channel_public` CHECK (`public_contact_channel_is_public` IN (0, 1))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

