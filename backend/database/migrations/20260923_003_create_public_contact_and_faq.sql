  CONSTRAINT `fk_contact_inquiry_company` FOREIGN KEY (`id_master_comp`) REFERENCES `master_comp` (`id_master_comp`) ON UPDATE CASCADE,
  CONSTRAINT `fk_contact_inquiry_selected_topic_company` FOREIGN KEY (`id_contact_inquiry_topic`, `id_master_comp`) REFERENCES `contact_inquiry_topic` (`id_contact_inquiry_topic`, `id_master_comp`) ON DELETE RESTRICT ON UPDATE CASCADE,
