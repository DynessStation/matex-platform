const fs = require("node:fs");
const path = require("node:path");
const dotenv = require("dotenv");

const adminRoot = path.resolve(__dirname, "..");
const envFile = path.resolve(
  adminRoot,
  process.env.MATEX_ADMIN_ENV_FILE || ".env.production",
);
const outputFile = path.join(
  adminRoot,
  "src/environments/environment.production.generated.ts",
);

if (fs.existsSync(envFile)) {
  const result = dotenv.config({ path: envFile, quiet: true });
  if (result.error) {
    throw result.error;
  }
}

function setting(name, fallback = "") {
  const value = process.env[name];
  return typeof value === "string" ? value.trim() : fallback;
}

const assetUrl = setting(
  "MATEX_ADMIN_ASSET_URL",
  "https://internal.matexindo.com/assets/data",
);
const apiUrl = setting("MATEX_ADMIN_API_URL", "https://internal.matexindo.com");
const environment = {
  production: true,
  URL: assetUrl,
  MOCK_URL: assetUrl,
  API_URL: apiUrl,
  GOOGLE_MAPS_API_KEY: setting("GOOGLE_MAPS_API_KEY"),
  GOOGLE_MAPS_MAP_ID: setting("GOOGLE_MAPS_MAP_ID"),
};

const source = `// Generated by scripts/generate-production-environment.cjs. Do not commit.\nexport const environment = ${JSON.stringify(environment, null, 2)};\n`;

fs.writeFileSync(outputFile, source, { encoding: "utf8", mode: 0o600 });
try {
  fs.chmodSync(outputFile, 0o600);
} catch {
  // Windows does not apply POSIX modes; the file remains excluded from Git.
}

console.log(
  `Generated admin production environment (Google Maps configured: ${environment.GOOGLE_MAPS_API_KEY ? "yes" : "no"}).`,
);
